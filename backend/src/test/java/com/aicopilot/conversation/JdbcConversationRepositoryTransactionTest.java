package com.aicopilot.conversation;

import com.aicopilot.knowledge.KnowledgeAgentStep;
import com.aicopilot.knowledge.KnowledgeRetrievalChunk;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.context.annotation.AnnotationConfigApplicationContext;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.dao.DataAccessException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;
import org.springframework.transaction.annotation.EnableTransactionManagement;

import javax.sql.DataSource;
import java.time.Instant;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * 用真实 JDBC（H2 内存库）+ 真实事务代理钉住 saveMessage 的原子性。
 *
 * <p>不能只用 Mockito：要验证的恰恰是「第二条 INSERT 失败时第一条会不会回滚」，
 * 这取决于有没有事务代理生效，mock 掉 JdbcTemplate 就把被测行为本身mock没了。
 */
class JdbcConversationRepositoryTransactionTest {

    private AnnotationConfigApplicationContext context;
    private JdbcTemplate jdbcTemplate;
    // 必须按接口取：@EnableTransactionManagement 默认用 JDK 动态代理，
    // 代理对象只暴露 ConversationRepository，getBean(JdbcConversationRepository.class) 取不到。
    private ConversationRepository repository;

    @BeforeEach
    void setUp() {
        context = new AnnotationConfigApplicationContext(TransactionTestConfiguration.class);
        jdbcTemplate = context.getBean(JdbcTemplate.class);
        repository = context.getBean(ConversationRepository.class);
        // created_at 不设默认值：saveMessage 现在显式写入该列；H2 会把「带默认值的列」
        // 也放进 generated keys，导致 keyHolder.getKey() 误判多键（MySQL 只返回自增列）。
        jdbcTemplate.execute("CREATE TABLE conversation_message ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "session_id BIGINT NOT NULL, role VARCHAR(32) NOT NULL, "
                + "content CLOB NOT NULL, created_at TIMESTAMP NOT NULL)");
        jdbcTemplate.execute("CREATE TABLE conversation_message_source ("
                + "message_id BIGINT NOT NULL, document_object_key VARCHAR(512) NOT NULL, "
                + "content CLOB NOT NULL, score DOUBLE, retriever VARCHAR(32))");
        jdbcTemplate.execute("CREATE TABLE conversation_message_agent_step ("
                + "message_id BIGINT NOT NULL, tool VARCHAR(64) NOT NULL, "
                + "query VARCHAR(1024) NOT NULL, result_count INT NOT NULL)");
    }

    @AfterEach
    void tearDown() {
        context.close();
    }

    @Test
    void savesMessageWithSourcesAndSteps() {
        ConversationMessage saved = repository.saveMessage(new ConversationMessage(
                null, 5L, "ASSISTANT", "回答", Instant.now(),
                List.of(new KnowledgeRetrievalChunk("kb/1/a.md", "片段", 0.9, "vector")),
                List.of(new KnowledgeAgentStep("knowledge_search", "检索关键词", 1))
        ));

        assertThat(saved.id()).isNotNull();
        assertThat(count("conversation_message")).isEqualTo(1);
        assertThat(count("conversation_message_source")).isEqualTo(1);
        assertThat(count("conversation_message_agent_step")).isEqualTo(1);
    }

    @Test
    void rollsBackMessageWhenSourceInsertFails() {
        // 来源对象键为 null 会撞 NOT NULL：主消息必须一起回滚，不能留下半成品助手消息
        assertThatThrownBy(() -> repository.saveMessage(new ConversationMessage(
                null, 5L, "ASSISTANT", "回答", Instant.now(),
                List.of(new KnowledgeRetrievalChunk(null, "片段", 0.9, "vector")),
                List.of()
        ))).isInstanceOf(DataAccessException.class);

        assertThat(count("conversation_message")).isZero();
        assertThat(count("conversation_message_source")).isZero();
    }

    private int count(String table) {
        Integer total = jdbcTemplate.queryForObject("SELECT COUNT(*) FROM " + table, Integer.class);
        return total == null ? 0 : total;
    }

    @Configuration
    @EnableTransactionManagement
    static class TransactionTestConfiguration {

        @Bean
        DataSource dataSource() {
            return new EmbeddedDatabaseBuilder()
                    .generateUniqueName(true)
                    .setType(EmbeddedDatabaseType.H2)
                    .build();
        }

        @Bean
        JdbcTemplate jdbcTemplate(DataSource dataSource) {
            return new JdbcTemplate(dataSource);
        }

        @Bean
        DataSourceTransactionManager transactionManager(DataSource dataSource) {
            return new DataSourceTransactionManager(dataSource);
        }

        @Bean
        JdbcConversationRepository conversationRepository(JdbcTemplate jdbcTemplate) {
            return new JdbcConversationRepository(jdbcTemplate);
        }
    }
}
